/** «7-6-1448» → «7 جمادى الآخرة 1448هـ» (like the original site: anything else gets the suffix as is). */
export function hijriText(h: string, S: Strings) {
  if (!h) return "";
  const r = /^(\d+)-(\d+)-(14\d\d)$/.exec(h);
  return r && +r[2] >= 1 && +r[2] <= 12 ? `${+r[1]} ${S.months[+r[2] - 1]} ${r[3]}${S.hijriSuffix}` : h + S.hijriSuffix;
}

